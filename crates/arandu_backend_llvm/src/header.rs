//! C header generation for `@Export` functions.
//!
//! The header is derived from the same `ArType` values and the same
//! `LayoutEngine` the ABI classifier uses, so a declaration can never describe
//! a layout the object does not implement. Every aggregate carries
//! `_Static_assert`s on size and field offsets: a C translation unit that
//! disagrees with Arandu fails to compile instead of corrupting memory.

use std::fmt::Write;

use arandu_middle::amir::AmirProgram;
use arandu_middle::layout::{StructLayoutProvider, TypeLayout, c_primitive_name};
use arandu_middle::types::TypeId;
use arandu_middle::types::{ArType, Primitive, TypeInterner};
use arandu_middle::{DiagCode, Diagnostic, LayoutEngine, SmolStr, SymbolId, SymbolTable};
use arandu_semantics::TypeInfo;

use crate::codegen::ice;

/// Renders a C header for every `@Export` function in `program`.
pub fn emit_c_header(
    program: &AmirProgram,
    symbols: &SymbolTable,
    info: &TypeInfo,
) -> Result<String, Diagnostic> {
    let interner = &info.type_interner;
    let layout = LayoutEngine::new(layout_pointer_width());
    let provider: &dyn StructLayoutProvider = info;

    let mut exported = program
        .funcs
        .iter()
        .filter(|function| symbols.is_exported(function.symbol))
        .map(|function| {
            (
                symbols
                    .host_func_name(symbols.get(function.symbol))
                    .to_owned(),
                function,
            )
        })
        .collect::<Vec<_>>();
    exported.sort_by(|left, right| left.0.cmp(&right.0));

    let mut declarations = Declarations::default();
    for (_, function) in &exported {
        for temp in &function.params {
            let ty = interner.resolve(function.temps[temp.as_usize()].ty);
            declarations.collect(&ty, interner, provider, symbols)?;
        }
        let return_ty = interner.resolve(function.return_type);
        declarations.collect(&return_ty, interner, provider, symbols)?;
    }

    let mut header = String::new();
    header.push_str("/* Generated by Arandu. Do not edit. */\n");
    header.push_str("#ifndef ARANDU_EXPORT_HEADER\n#define ARANDU_EXPORT_HEADER\n\n");
    header.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");
    header.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");

    let mut struct_names = declarations
        .structs
        .iter()
        .map(|symbol| symbols.get(*symbol).name.clone())
        .collect::<Vec<_>>();
    struct_names.sort();
    struct_names.dedup();
    for name in &struct_names {
        let _ = writeln!(header, "typedef struct {name} {name};");
    }
    if !struct_names.is_empty() {
        header.push('\n');
    }

    let mut slices = declarations.slices.clone();
    slices.sort_by(|left, right| left.name.cmp(&right.name));
    slices.dedup_by(|left, right| left.name == right.name);
    for slice in &slices {
        let element = c_type(&slice.element, symbols, interner, &layout)?;
        let qualifier = if slice.mutable { "" } else { "const " };
        let _ = writeln!(
            header,
            "typedef struct {{ {qualifier}{element} *ptr; size_t len; }} {};",
            slice.name
        );
    }
    if !slices.is_empty() {
        header.push('\n');
    }

    for symbol in &declarations.structs {
        emit_struct(&mut header, *symbol, symbols, interner, provider, &layout)?;
    }

    for (name, function) in &exported {
        let mut parameters = Vec::with_capacity(function.params.len());
        for temp in &function.params {
            let ty = interner.resolve(function.temps[temp.as_usize()].ty);
            parameters.push(c_type(&ty, symbols, interner, &layout)?);
        }
        let return_ty = interner.resolve(function.return_type);
        let return_text = match &return_ty {
            ArType::Void => "void".to_owned(),
            other => c_type(other, symbols, interner, &layout)?,
        };
        let parameters = if parameters.is_empty() {
            "void".to_owned()
        } else {
            parameters.join(", ")
        };
        let _ = writeln!(header, "{return_text} {name}({parameters});");
    }

    header.push_str("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* ARANDU_EXPORT_HEADER */\n");
    Ok(header)
}

/// Pointer width of the host, matching the object a host build produces.
fn layout_pointer_width() -> u64 {
    if std::mem::size_of::<usize>() == 4 {
        4
    } else {
        8
    }
}

/// A slice typedef: C element type plus the typedef name.
#[derive(Clone)]
struct SliceDecl {
    element: ArType,
    name: String,
    mutable: bool,
}

/// Nominal types reachable from exported signatures, dependencies first.
#[derive(Default)]
struct Declarations {
    structs: Vec<SymbolId>,
    slices: Vec<SliceDecl>,
}

impl Declarations {
    fn collect(
        &mut self,
        ty: &ArType,
        interner: &TypeInterner,
        provider: &dyn StructLayoutProvider,
        symbols: &SymbolTable,
    ) -> Result<(), Diagnostic> {
        match ty {
            ArType::Named(symbol, _) => {
                if self.structs.contains(symbol) {
                    return Ok(());
                }
                self.structs.push(*symbol);
                if let Some(fields) = provider.get_struct_fields_for_type(ty, interner) {
                    for field in &fields.fields {
                        let field_ty = interner.resolve(field.ty);
                        self.collect(&field_ty, interner, provider, symbols)?;
                    }
                }
            }
            ArType::Slice(element) | ArType::MutSlice(element) => {
                let element_ty = interner.resolve(*element);
                self.collect(&element_ty, interner, provider, symbols)?;
                let name = format!("AranduSlice{}", slice_label(&element_ty, symbols));
                if !self.slices.iter().any(|slice| slice.name == name) {
                    self.slices.push(SliceDecl {
                        element: element_ty,
                        name,
                        mutable: matches!(ty, ArType::MutSlice(_)),
                    });
                }
            }
            ArType::Ptr(inner) => {
                let inner_ty = interner.resolve(*inner);
                self.collect(&inner_ty, interner, provider, symbols)?;
            }
            _ => {}
        }
        Ok(())
    }
}

/// Stable C identifier fragment for a slice element type.
fn slice_label(ty: &ArType, symbols: &SymbolTable) -> SmolStr {
    let label = match ty {
        ArType::Primitive(primitive) => match primitive {
            Primitive::Bool => "Bool",
            Primitive::I8 => "I8",
            Primitive::I16 => "I16",
            Primitive::I32 => "I32",
            Primitive::I64 => "I64",
            Primitive::U8 | Primitive::Byte => "U8",
            Primitive::U16 => "U16",
            Primitive::U32 | Primitive::Char => "U32",
            Primitive::U64 => "U64",
            Primitive::F32 => "F32",
            Primitive::F64 | Primitive::Float => "F64",
            other => return SmolStr::new(format!("{other:?}")),
        },
        ArType::Named(symbol, _) => return SmolStr::new(symbols.get(*symbol).name.as_str()),
        ArType::Ptr(_) => "Ptr",
        other => return SmolStr::new(format!("{other:?}")),
    };
    SmolStr::new(label)
}

fn emit_struct(
    header: &mut String,
    symbol: SymbolId,
    symbols: &SymbolTable,
    interner: &TypeInterner,
    provider: &dyn StructLayoutProvider,
    layout: &LayoutEngine,
) -> Result<(), Diagnostic> {
    let name = symbols.get(symbol).name.clone();
    let ty = ArType::named(symbol, &[], interner);
    let fields = provider
        .get_struct_fields_for_type(&ty, interner)
        .ok_or_else(|| ice(format!("struct {name} has no field layout")))?;
    let type_layout: TypeLayout = layout
        .layout_of_type(&ty, interner, provider)
        .map_err(|error| ice(format!("struct {name} has no layout: {error}")))?;

    let _ = writeln!(header, "struct {name} {{");
    for field in &fields.fields {
        let field_ty = interner.resolve(field.ty);
        let text = c_type(&field_ty, symbols, interner, layout)?;
        let _ = writeln!(header, "    {text} {};", field.name);
    }
    header.push_str("};\n");
    let _ = writeln!(
        header,
        "_Static_assert(sizeof({name}) == {}, \"{name} must match Arandu's layout\");",
        type_layout.size.max(1)
    );
    for (field, offset) in fields.fields.iter().zip(&type_layout.field_offsets) {
        let _ = writeln!(
            header,
            "_Static_assert(offsetof({name}, {}) == {offset}, \"{name}.{} must match Arandu's layout\");",
            field.name, field.name
        );
    }
    header.push('\n');
    Ok(())
}

fn c_type(
    ty: &ArType,
    symbols: &SymbolTable,
    interner: &TypeInterner,
    layout: &LayoutEngine,
) -> Result<String, Diagnostic> {
    let pointer_width = layout.pointer_width();
    let text = match ty {
        ArType::Primitive(primitive) => {
            c_primitive_name(*primitive, pointer_width).ok_or_else(|| unsupported(primitive))?
        }
        ArType::Named(symbol, _) => symbols.get(*symbol).name.to_string(),
        ArType::Ptr(inner) => {
            let inner_ty = interner.resolve(*inner);
            if matches!(inner_ty, ArType::Void) {
                "void *".to_owned()
            } else {
                format!(
                    "{} *",
                    c_type(&inner_ty, symbols, interner, layout)?
                )
            }
        }
        ArType::Void => "void".to_owned(),
        ArType::Slice(element) | ArType::MutSlice(element) => {
            let element_ty = interner.resolve(*element);
            format!("AranduSlice{}", slice_label(&element_ty, symbols))
        }
        other => {
            return Err(Diagnostic::error(
                DiagCode::T049InvalidFfiExport,
                format!("{other:?} has no C representation"),
                arandu_middle::Span::new(0, 0, 0),
            ));
        }
    };
    Ok(text)
}

fn unsupported(primitive: &Primitive) -> Diagnostic {
    Diagnostic::error(
        DiagCode::T049InvalidFfiExport,
        format!("{primitive:?} has no fixed-width C representation"),
        arandu_middle::Span::new(0, 0, 0),
    )
}

/// Layout of a type as C sees it.
#[must_use]
pub fn c_size_of(
    ty: &ArType,
    interner: &TypeInterner,
    provider: &dyn StructLayoutProvider,
    layout: &LayoutEngine,
) -> Option<TypeLayout> {
    layout.layout_of_type(ty, interner, provider).ok()
}

/// Element type of a slice.
#[must_use]
pub fn slice_element_of(ty: &ArType) -> Option<TypeId> {
    match ty {
        ArType::Slice(element) | ArType::MutSlice(element) => Some(*element),
        _ => None,
    }
}
